-- Chạy trên Oracle XE/XEPDB1 với user TRAVELGO

-- ========================= SEQUENCES =========================
CREATE SEQUENCE SEQ_USERS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_ROLES START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_CATEGORIES START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_DESTINATIONS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TOURS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TOUR_IMAGES START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TOUR_ITINERARIES START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TOUR_SCHEDULES START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_BOOKINGS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_BOOKING_GUESTS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_PAYMENTS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_COUPONS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_FAVORITES START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_REVIEWS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_POST_CATEGORIES START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_POSTS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_POST_COMMENTS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TOUR_QA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_QA_REPLIES START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

-- ========================= TABLES =========================
CREATE TABLE ROLES (
    ID NUMBER(19) PRIMARY KEY,
    NAME VARCHAR2(50) NOT NULL,
    CONSTRAINT UK_ROLES_NAME UNIQUE (NAME),
    CONSTRAINT CK_ROLES_NAME CHECK (NAME IN ('ADMIN', 'STAFF', 'CUSTOMER'))
);

CREATE TABLE USERS (
    ID NUMBER(19) PRIMARY KEY,
    FULL_NAME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    PHONE VARCHAR2(20),
    DATE_OF_BIRTH DATE,
    GENDER VARCHAR2(20),
    ADDRESS VARCHAR2(255),
    AVATAR VARCHAR2(500),
    PASSWORD VARCHAR2(255) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    RESET_TOKEN VARCHAR2(255),
    RESET_TOKEN_EXPIRY TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_GENDER CHECK (GENDER IN ('MALE', 'FEMALE', 'OTHER') OR GENDER IS NULL),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'LOCKED'))
);

CREATE TABLE USER_ROLES (
    USER_ID NUMBER(19) NOT NULL,
    ROLE_ID NUMBER(19) NOT NULL,
    CONSTRAINT PK_USER_ROLES PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_USER_ROLES_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_USER_ROLES_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ID)
);

CREATE TABLE CATEGORIES (
    ID NUMBER(19) PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT UK_CATEGORIES_NAME UNIQUE (NAME),
    CONSTRAINT CK_CATEGORIES_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE DESTINATIONS (
    ID NUMBER(19) PRIMARY KEY,
    NAME VARCHAR2(150) NOT NULL,
    PROVINCE VARCHAR2(150) NOT NULL,
    DESCRIPTION CLOB,
    IMAGE VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT UK_DESTINATIONS_NAME UNIQUE (NAME),
    CONSTRAINT CK_DESTINATIONS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE TOURS (
    ID NUMBER(19) PRIMARY KEY,
    CODE VARCHAR2(50) NOT NULL,
    NAME VARCHAR2(255) NOT NULL,
    CATEGORY_ID NUMBER(19) NOT NULL,
    DESTINATION_ID NUMBER(19) NOT NULL,
    DESCRIPTION CLOB,
    DURATION_DAYS NUMBER(3) NOT NULL,
    DURATION_NIGHTS NUMBER(3) NOT NULL,
    ORIGINAL_PRICE NUMBER(14,2),
    ADULT_PRICE NUMBER(14,2) NOT NULL,
    CHILD_PRICE NUMBER(14,2) NOT NULL,
    INFANT_PRICE NUMBER(14,2) DEFAULT 0 NOT NULL,
    MAX_PEOPLE NUMBER(5) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    AVERAGE_RATING NUMBER(3,2) DEFAULT 0,
    REVIEW_COUNT NUMBER(10) DEFAULT 0,
    FEATURED NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT UK_TOURS_CODE UNIQUE (CODE),
    CONSTRAINT FK_TOURS_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES (ID),
    CONSTRAINT FK_TOURS_DESTINATION FOREIGN KEY (DESTINATION_ID) REFERENCES DESTINATIONS (ID),
    CONSTRAINT CK_TOURS_STATUS CHECK (STATUS IN ('ACTIVE', 'HIDDEN')),
    CONSTRAINT CK_TOURS_ADULT_PRICE CHECK (ADULT_PRICE > 0),
    CONSTRAINT CK_TOURS_CHILD_PRICE CHECK (CHILD_PRICE >= 0),
    CONSTRAINT CK_TOURS_INFANT_PRICE CHECK (INFANT_PRICE >= 0),
    CONSTRAINT CK_TOURS_DURATION CHECK (DURATION_DAYS > 0),
    CONSTRAINT CK_TOURS_MAX_PEOPLE CHECK (MAX_PEOPLE > 0),
    CONSTRAINT CK_TOURS_FEATURED CHECK (FEATURED IN (0, 1))
);

CREATE TABLE TOUR_IMAGES (
    ID NUMBER(19) PRIMARY KEY,
    TOUR_ID NUMBER(19) NOT NULL,
    IMAGE_URL VARCHAR2(500) NOT NULL,
    IS_COVER NUMBER(1) DEFAULT 0 NOT NULL,
    SORT_ORDER NUMBER(5) DEFAULT 0,
    CONSTRAINT FK_TOUR_IMAGES_TOUR FOREIGN KEY (TOUR_ID) REFERENCES TOURS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_TOUR_IMAGES_COVER CHECK (IS_COVER IN (0, 1))
);

CREATE TABLE TOUR_ITINERARIES (
    ID NUMBER(19) PRIMARY KEY,
    TOUR_ID NUMBER(19) NOT NULL,
    DAY_NUMBER NUMBER(3) NOT NULL,
    TITLE VARCHAR2(255) NOT NULL,
    DESCRIPTION CLOB,
    CONSTRAINT FK_TOUR_ITINERARIES_TOUR FOREIGN KEY (TOUR_ID) REFERENCES TOURS (ID) ON DELETE CASCADE,
    CONSTRAINT UK_TOUR_ITINERARY UNIQUE (TOUR_ID, DAY_NUMBER),
    CONSTRAINT CK_ITINERARY_DAY CHECK (DAY_NUMBER > 0)
);

CREATE TABLE TOUR_SCHEDULES (
    ID NUMBER(19) PRIMARY KEY,
    TOUR_ID NUMBER(19) NOT NULL,
    DEPARTURE_DATE DATE NOT NULL,
    RETURN_DATE DATE NOT NULL,
    TOTAL_SEATS NUMBER(5) NOT NULL,
    AVAILABLE_SEATS NUMBER(5) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    CONSTRAINT FK_TOUR_SCHEDULES_TOUR FOREIGN KEY (TOUR_ID) REFERENCES TOURS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_SCHEDULE_SEATS CHECK (TOTAL_SEATS > 0),
    CONSTRAINT CK_SCHEDULE_AVAILABLE CHECK (AVAILABLE_SEATS >= 0),
    CONSTRAINT CK_SCHEDULE_STATUS CHECK (STATUS IN ('OPEN', 'CLOSED', 'CANCELLED'))
);

CREATE TABLE COUPONS (
    ID NUMBER(19) PRIMARY KEY,
    CODE VARCHAR2(50) NOT NULL,
    NAME VARCHAR2(150) NOT NULL,
    DISCOUNT_PERCENT NUMBER(5,2) NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    MAX_USAGE NUMBER(10) NOT NULL,
    USED_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT UK_COUPONS_CODE UNIQUE (CODE),
    CONSTRAINT CK_COUPONS_PERCENT CHECK (DISCOUNT_PERCENT > 0 AND DISCOUNT_PERCENT <= 100),
    CONSTRAINT CK_COUPONS_MAX CHECK (MAX_USAGE > 0),
    CONSTRAINT CK_COUPONS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE BOOKINGS (
    ID NUMBER(19) PRIMARY KEY,
    BOOKING_CODE VARCHAR2(30) NOT NULL,
    USER_ID NUMBER(19) NOT NULL,
    TOUR_ID NUMBER(19) NOT NULL,
    SCHEDULE_ID NUMBER(19) NOT NULL,
    COUPON_ID NUMBER(19),
    ADULT_COUNT NUMBER(5) NOT NULL,
    CHILD_COUNT NUMBER(5) DEFAULT 0 NOT NULL,
    INFANT_COUNT NUMBER(5) DEFAULT 0 NOT NULL,
    SUBTOTAL NUMBER(14,2) NOT NULL,
    DISCOUNT_AMOUNT NUMBER(14,2) DEFAULT 0 NOT NULL,
    TOTAL_AMOUNT NUMBER(14,2) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT UK_BOOKINGS_CODE UNIQUE (BOOKING_CODE),
    CONSTRAINT FK_BOOKINGS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_BOOKINGS_TOUR FOREIGN KEY (TOUR_ID) REFERENCES TOURS (ID),
    CONSTRAINT FK_BOOKINGS_SCHEDULE FOREIGN KEY (SCHEDULE_ID) REFERENCES TOUR_SCHEDULES (ID),
    CONSTRAINT FK_BOOKINGS_COUPON FOREIGN KEY (COUPON_ID) REFERENCES COUPONS (ID),
    CONSTRAINT CK_BOOKINGS_ADULT CHECK (ADULT_COUNT > 0),
    CONSTRAINT CK_BOOKINGS_CHILD CHECK (CHILD_COUNT >= 0),
    CONSTRAINT CK_BOOKINGS_INFANT CHECK (INFANT_COUNT >= 0),
    CONSTRAINT CK_BOOKINGS_TOTAL CHECK (TOTAL_AMOUNT >= 0),
    CONSTRAINT CK_BOOKINGS_STATUS CHECK (STATUS IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'COMPLETED'))
);

CREATE TABLE BOOKING_GUESTS (
    ID NUMBER(19) PRIMARY KEY,
    BOOKING_ID NUMBER(19) NOT NULL,
    FULL_NAME VARCHAR2(150) NOT NULL,
    DATE_OF_BIRTH DATE,
    GENDER VARCHAR2(20),
    PHONE VARCHAR2(20),
    EMAIL VARCHAR2(150),
    IDENTITY_NUMBER VARCHAR2(50),
    CONSTRAINT FK_BOOKING_GUESTS_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_GUESTS_GENDER CHECK (GENDER IN ('MALE', 'FEMALE', 'OTHER') OR GENDER IS NULL)
);

CREATE TABLE PAYMENTS (
    ID NUMBER(19) PRIMARY KEY,
    BOOKING_ID NUMBER(19) NOT NULL,
    METHOD VARCHAR2(30) NOT NULL,
    AMOUNT NUMBER(14,2) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    TRANSACTION_REF VARCHAR2(100),
    PAID_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_PAYMENTS_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS (ID),
    CONSTRAINT CK_PAYMENTS_METHOD CHECK (METHOD IN ('CASH', 'BANK_TRANSFER', 'ONLINE')),
    CONSTRAINT CK_PAYMENTS_STATUS CHECK (STATUS IN ('PENDING', 'PAID', 'FAILED', 'REFUNDED')),
    CONSTRAINT CK_PAYMENTS_AMOUNT CHECK (AMOUNT >= 0)
);

CREATE TABLE FAVORITES (
    ID NUMBER(19) PRIMARY KEY,
    USER_ID NUMBER(19) NOT NULL,
    TOUR_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_FAVORITES_USER_TOUR UNIQUE (USER_ID, TOUR_ID),
    CONSTRAINT FK_FAVORITES_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_FAVORITES_TOUR FOREIGN KEY (TOUR_ID) REFERENCES TOURS (ID)
);

CREATE TABLE REVIEWS (
    ID NUMBER(19) PRIMARY KEY,
    USER_ID NUMBER(19) NOT NULL,
    TOUR_ID NUMBER(19) NOT NULL,
    BOOKING_ID NUMBER(19) NOT NULL,
    RATING NUMBER(1) NOT NULL,
    REVIEW_COMMENT VARCHAR2(2000),
    STATUS VARCHAR2(20) DEFAULT 'VISIBLE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_REVIEWS_BOOKING UNIQUE (BOOKING_ID),
    CONSTRAINT FK_REVIEWS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_REVIEWS_TOUR FOREIGN KEY (TOUR_ID) REFERENCES TOURS (ID),
    CONSTRAINT FK_REVIEWS_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS (ID),
    CONSTRAINT CK_REVIEWS_RATING CHECK (RATING BETWEEN 1 AND 5),
    CONSTRAINT CK_REVIEWS_STATUS CHECK (STATUS IN ('VISIBLE', 'HIDDEN'))
);

-- Bảng mới: Danh mục bài viết
CREATE TABLE POST_CATEGORIES (
    ID NUMBER(19) PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    SLUG VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_POST_CATEGORIES_NAME UNIQUE (NAME),
    CONSTRAINT UK_POST_CATEGORIES_SLUG UNIQUE (SLUG),
    CONSTRAINT CK_POST_CATEGORIES_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

-- Bảng mới: Bài viết/Tin tức
CREATE TABLE POSTS (
    ID NUMBER(19) PRIMARY KEY,
    TITLE VARCHAR2(255) NOT NULL,
    SLUG VARCHAR2(255) NOT NULL,
    EXCERPT VARCHAR2(500),
    CONTENT CLOB NOT NULL,
    THUMBNAIL VARCHAR2(500),
    AUTHOR_ID NUMBER(19) NOT NULL,
    CATEGORY_ID NUMBER(19) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
    VIEW_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    FEATURED NUMBER(1) DEFAULT 0 NOT NULL,
    PUBLISHED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT UK_POSTS_SLUG UNIQUE (SLUG),
    CONSTRAINT FK_POSTS_AUTHOR FOREIGN KEY (AUTHOR_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_POSTS_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES POST_CATEGORIES (ID),
    CONSTRAINT CK_POSTS_STATUS CHECK (STATUS IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    CONSTRAINT CK_POSTS_FEATURED CHECK (FEATURED IN (0, 1))
);

-- Bảng mới: Bình luận bài viết
CREATE TABLE POST_COMMENTS (
    ID NUMBER(19) PRIMARY KEY,
    POST_ID NUMBER(19) NOT NULL,
    USER_ID NUMBER(19) NOT NULL,
    CONTENT VARCHAR2(1000) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'VISIBLE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_POST_COMMENTS_POST FOREIGN KEY (POST_ID) REFERENCES POSTS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_POST_COMMENTS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT CK_POST_COMMENTS_STATUS CHECK (STATUS IN ('VISIBLE', 'HIDDEN'))
);

-- Bảng mới: Hỏi đáp về tour
CREATE TABLE TOUR_QA (
    ID NUMBER(19) PRIMARY KEY,
    TOUR_ID NUMBER(19) NOT NULL,
    USER_ID NUMBER(19) NOT NULL,
    QUESTION VARCHAR2(1000) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'VISIBLE' NOT NULL,
    REPLY_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT FK_TOUR_QA_TOUR FOREIGN KEY (TOUR_ID) REFERENCES TOURS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_TOUR_QA_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT CK_TOUR_QA_STATUS CHECK (STATUS IN ('VISIBLE', 'HIDDEN'))
);

-- Bảng mới: Trả lời hỏi đáp
CREATE TABLE QA_REPLIES (
    ID NUMBER(19) PRIMARY KEY,
    QA_ID NUMBER(19) NOT NULL,
    USER_ID NUMBER(19) NOT NULL,
    REPLY VARCHAR2(2000) NOT NULL,
    IS_ANSWER NUMBER(1) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'VISIBLE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT FK_QA_REPLIES_QA FOREIGN KEY (QA_ID) REFERENCES TOUR_QA (ID) ON DELETE CASCADE,
    CONSTRAINT FK_QA_REPLIES_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT CK_QA_REPLIES_ANSWER CHECK (IS_ANSWER IN (0, 1)),
    CONSTRAINT CK_QA_REPLIES_STATUS CHECK (STATUS IN ('VISIBLE', 'HIDDEN'))
);

