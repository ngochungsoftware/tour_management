    ID NUMBER(19) PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    SLUG VARCHAR2(100) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_TOUR_TAGS_NAME UNIQUE (NAME),
    CONSTRAINT UK_TOUR_TAGS_SLUG UNIQUE (SLUG),
    CONSTRAINT CK_TOUR_TAGS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

-- ========================= 9. TOUR_TAG_MAP – Gán nhãn cho tour =========================
CREATE TABLE TOUR_TAG_MAP (
    ID NUMBER(19) PRIMARY KEY,
    TOUR_ID NUMBER(19) NOT NULL,
    TAG_ID NUMBER(19) NOT NULL,
    CONSTRAINT UK_TOUR_TAG_MAP UNIQUE (TOUR_ID, TAG_ID),
    CONSTRAINT FK_TOUR_TAG_MAP_TOUR FOREIGN KEY (TOUR_ID) REFERENCES TOURS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_TOUR_TAG_MAP_TAG FOREIGN KEY (TAG_ID) REFERENCES TOUR_TAGS (ID) ON DELETE CASCADE
